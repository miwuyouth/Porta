import Foundation

public final class FRPConfigGenerator {
    /// Generates modern frpc.toml configuration string (frp v0.52.0+)
    public static func generateToml(server: FRPServer, proxies: [FRPProxy], settings: AppSettings) -> String {
        var lines: [String] = []

        lines.append("# Auto-generated by Porta")
        lines.append("serverAddr = \"\(server.serverAddr)\"")
        lines.append("serverPort = \(server.serverPort)")

        if !server.token.isEmpty {
            lines.append("auth.method = \"token\"")
            lines.append("auth.token = \"\(server.token)\"")
        }

        if server.tlsEnable {
            lines.append("transport.tls.enable = true")
        }

        if server.transportProtocol != "tcp" {
            lines.append("transport.protocol = \"\(server.transportProtocol)\"")
        }

        // Logging configuration
        lines.append("log.to = \"console\"")
        lines.append("log.level = \"\(settings.logLevel.lowercased())\"")
        lines.append("log.disablePrintColor = true")

        lines.append("")

        // Only enabled proxies are generated
        for proxy in proxies where proxy.isEnabled {
            lines.append("[[proxies]]")
            // Create a safe identifier name for frpc proxy
            let safeName = sanitizeProxyName(proxy.name)
            lines.append("name = \"\(safeName)\"")
            lines.append("type = \"\(proxy.type.rawValue)\"")
            lines.append("localIP = \"\(proxy.localIP)\"")
            lines.append("localPort = \(proxy.localPort)")

            switch proxy.type {
            case .tcp, .udp:
                if let remote = proxy.remotePort {
                    lines.append("remotePort = \(remote)")
                }
            case .http, .https:
                if let custom = proxy.customDomains, !custom.isEmpty {
                    let domainList = custom.split(separator: ",").map { "\"\(String($0).trimmingCharacters(in: .whitespaces))\"" }.joined(separator: ", ")
                    lines.append("customDomains = [\(domainList)]")
                }
                if let sub = proxy.subdomain, !sub.isEmpty {
                    lines.append("subdomain = \"\(sub)\"")
                }
            case .stcp, .xtcp:
                if let remote = proxy.remotePort {
                    lines.append("remotePort = \(remote)")
                }
                lines.append("secretKey = \"\(server.token)\"")
            }

            if proxy.useEncryption {
                lines.append("transport.useEncryption = true")
            }
            if proxy.useCompression {
                lines.append("transport.useCompression = true")
            }

            lines.append("")
        }

        return lines.joined(separator: "\n")
    }

    public static func sanitizeProxyName(_ name: String) -> String {
        // Map common names to clean ascii tags if needed, or transliterate
        let trimmed = name.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed == "Web 服务" { return "web" }
        if trimmed == "SSH" { return "ssh" }
        if trimmed == "开发预览" { return "dev" }

        // Remove spaces and punctuation
        let allowed = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: "-_"))
        let filtered = trimmed.components(separatedBy: allowed.inverted).joined()
        return filtered.isEmpty ? "proxy_\(abs(name.hashValue % 10000))" : filtered.lowercased()
    }
}
